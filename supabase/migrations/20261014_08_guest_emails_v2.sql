-- 3) A cancelled confirmed booking emails the guest ---------------------------------------------
create or replace function public.queue_guest_email()
returns trigger
language plpgsql
security definer
set search_path = public, vault, net
as $$
declare k text;
begin
  if tg_op = 'INSERT' then
    if new.status = 'pending' then k := 'received'; end if;
  elsif new.status is distinct from old.status then
    if old.status = 'pending' and new.status in ('confirmed', 'rejected', 'expired') then
      k := new.status;
    elsif old.status = 'confirmed' and new.status = 'cancelled' then
      k := 'cancelled';
    end if;
  end if;
  if k is null then return new; end if;

  begin
    perform net.http_post(
      url := 'https://cwucmglctgklokxwbwqz.supabase.co/functions/v1/send-email',
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'cron_secret')
      ),
      body := jsonb_build_object('request_id', new.id, 'kind', k),
      timeout_milliseconds := 20000
    );
  exception when others then
    raise warning 'queue_guest_email failed: %', sqlerrm;
  end;
  return new;
end
$$;
revoke all on function public.queue_guest_email() from public, anon, authenticated;

-- 4) Offers: who may receive them, who opted out, what was scheduled and sent -----------------
create table if not exists public.marketing_optouts (
  email text primary key check (email = lower(email)),
  created_at timestamptz not null default now()
);
alter table public.marketing_optouts enable row level security;
revoke all on public.marketing_optouts from anon, authenticated;

create table if not exists public.promo_offers (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  discount_pct smallint not null check (discount_pct between 1 and 90),
  code text check (code is null or code ~ '^[A-Za-z0-9_-]{3,24}$'),
  stay_from date not null,
  stay_to date not null,
  book_by date,
  send_at timestamptz not null,
  status text not null default 'scheduled' check (status in ('scheduled', 'sending', 'sent', 'cancelled')),
  sent_count integer not null default 0,
  failed_count integer not null default 0,
  lease_until timestamptz,
  finished_at timestamptz,
  constraint promo_stay_order check (stay_to >= stay_from),
  constraint promo_book_by_order check (book_by is null or book_by <= stay_to)
);
alter table public.promo_offers enable row level security;
revoke all on public.promo_offers from anon, authenticated;
grant select on public.promo_offers to authenticated;
grant insert (discount_pct, code, stay_from, stay_to, book_by, send_at) on public.promo_offers to authenticated;
grant update (status) on public.promo_offers to authenticated;
create policy "owners read offers" on public.promo_offers for select to authenticated using (public.is_owner());
create policy "owners add offers" on public.promo_offers for insert to authenticated with check (public.is_owner());
create policy "owners cancel scheduled offers" on public.promo_offers for update to authenticated
  using (public.is_owner() and status = 'scheduled') with check (public.is_owner() and status = 'cancelled');

create table if not exists public.promo_sends (
  offer_id uuid not null references public.promo_offers (id) on delete cascade,
  email text not null,
  status text not null check (status in ('sent', 'failed')),
  attempts smallint not null default 1,
  error text,
  provider_id text,
  updated_at timestamptz not null default now(),
  primary key (offer_id, email)
);
alter table public.promo_sends enable row level security;
revoke all on public.promo_sends from anon, authenticated;
grant select on public.promo_sends to authenticated;
create policy "owners read offer sends" on public.promo_sends for select to authenticated using (public.is_owner());

-- Guests who stayed (confirmed, not a test, check-out passed), whose latest stay carried the
-- marketing tick, and who have not unsubscribed. One row per email, newest stay wins.
create or replace function public.promo_audience()
returns table (email text, name text, lang text)
language sql
stable
security definer
set search_path = public
as $$
  select l.email, l.name, l.lang
  from (
    select distinct on (lower(r.email)) lower(r.email) as email, r.name, r.lang, r.marketing_consent
    from public.booking_requests r
    where r.status = 'confirmed' and not r.is_test
      and r.check_out < (now() at time zone 'Europe/Athens')::date
    order by lower(r.email), r.check_out desc, r.created_at desc
  ) l
  where l.marketing_consent
    and not exists (select 1 from public.marketing_optouts o where o.email = l.email);
$$;
revoke all on function public.promo_audience() from public, anon, authenticated;

create or replace function public.promo_audience_count()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select case when public.is_owner() then (select count(*)::int from public.promo_audience()) end;
$$;
revoke all on function public.promo_audience_count() from public, anon;
grant execute on function public.promo_audience_count() to authenticated;

